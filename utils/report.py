"""Markdown report generator."""
from __future__ import annotations
from datetime import datetime


def generate_markdown_report(result: dict) -> str:
    score_summary = result.get("score_summary")
    score = score_summary.health_score if score_summary else "N/A"
    total = score_summary.total_issues if score_summary else 0
    critical = score_summary.critical_count if score_summary else 0
    warnings = score_summary.warning_count if score_summary else 0
    suggestions = score_summary.suggestion_count if score_summary else 0

    ts = datetime.now().strftime("%Y-%m-%d %H:%M")
    name = result.get("repo_url") or "Uploaded File"

    lines = [
        f"# ReviewBot Report — {name}",
        f"**Generated:** {ts}  ",
        f"**Health Score:** {score}/100  ",
        f"**Files Reviewed:** {result.get('files_reviewed', 0)}\n",
        "---\n",
        "## Summary\n",
        "| Metric | Count |",
        "|--------|-------|",
        f"| 🔴 Critical | {critical} |",
        f"| 🟡 Warning  | {warnings} |",
        f"| 🔵 Suggestion | {suggestions} |",
        f"| **Total** | **{total}** |\n",
        "---\n",
        "## Issues by File\n",
    ]

    for fr in result.get("file_results", []):
        lines.append(f"### 📄 `{fr.get('filename', 'Unknown')}`\n")
        issues = fr.get("issues", [])
        if not issues:
            lines.append("✅ No issues found.\n")
            continue
        for issue in issues:
            sev = issue.get("severity", "?")
            badge = {"CRITICAL": "🔴", "WARNING": "🟡", "SUGGESTION": "🔵"}.get(sev, "⚪")
            lines.append(f"#### {badge} {issue.get('title', 'Issue')}")
            lines.append(f"- **Severity:** {sev}")
            lines.append(f"- **Line:** {issue.get('line', '?')}")
            lines.append(f"- **Description:** {issue.get('description', '')}")
            lines.append(f"- **Root Cause:** {issue.get('root_cause', '')}\n")
            if issue.get("before_code"):
                lines.append(f"**Before:**\n```{issue.get('language','')}\n{issue['before_code']}\n```")
            if issue.get("after_code"):
                lines.append(f"**After:**\n```{issue.get('language','')}\n{issue['after_code']}\n```\n")

    lines += ["---", "*Generated by ReviewBot — AI Code Review for Serious Engineers*"]
    return "\n".join(lines)
